import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const rootDir = resolve(import.meta.dirname, '..')
const componentsDir = resolve(rootDir, 'src/components')
const stylesDir = resolve(rootDir, 'src/styles')
const generatedDir = resolve(rootDir, 'src/generated')
const checkOnly = process.argv.includes('--check')
const packageFile = resolve(rootDir, 'package.json')
const rootPackage = JSON.parse(await readFile(packageFile, 'utf8'))
const metadata = JSON.parse(await readFile(resolve(rootDir, 'scripts/component-metadata.json'), 'utf8'))
const publicEntries = JSON.parse(await readFile(resolve(rootDir, 'scripts/public-entries.json'), 'utf8'))

const componentNames = (await readdir(componentsDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^Mc[A-Z]/.test(entry.name))
  .map((entry) => entry.name)
  .sort()
const sharedStyles = (await readdir(resolve(stylesDir, 'shared'), { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith('.css'))
  .map((entry) => entry.name)
  .sort()

const metadataNames = Object.keys(metadata).sort()
if (JSON.stringify(metadataNames) !== JSON.stringify(componentNames)) {
  throw new Error('scripts/component-metadata.json keys must exactly match src/components/Mc* directories')
}

function kebabCase(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

async function emit(file, output) {
  if (checkOnly) {
    const current = await readFile(file, 'utf8')
    if (current !== output) throw new Error(`${file} is stale; run npm run generate`)
  } else {
    await mkdir(resolve(file, '..'), { recursive: true })
    await writeFile(file, output, 'utf8')
  }
}

for (const componentName of componentNames) {
  const componentDir = resolve(componentsDir, componentName)
  const vueFile = resolve(componentDir, `${componentName}.vue`)
  const componentCss = await readFile(resolve(componentDir, 'component.css'), 'utf8')
  let vue = await readFile(vueFile, 'utf8')
  const cssImports = [
    "import '../../styles/component-core.css'",
    ...(vue.includes('class="mc-input') ? ["import '../../styles/shared/input-control.css'"] : []),
    ...(componentCss.includes('{') ? ["import './style.css'"] : []),
  ]
  const entry = [`export { default } from './${componentName}.vue'`, `export * from './${componentName}.vue'`, ''].join(
    '\n',
  )
  const style = "@import './component.css';\n"
  const hasCssImports = cssImports.every((cssImport) => vue.includes(cssImport))
  if (!hasCssImports || vue.includes("import './styles'")) {
    if (checkOnly) throw new Error(`${vueFile} must import its generated CSS dependencies`)
    vue = vue.replace("import './styles'\n", '')
    vue = vue.replace(/<script(?:\s+setup)?(?:\s+lang="ts")?>\r?\n/, (match) => `${match}${cssImports.join('\n')}\n`)
    await writeFile(vueFile, vue, 'utf8')
  }
  await emit(resolve(componentDir, 'index.ts'), entry)
  await emit(resolve(componentDir, 'style.css'), style)
  if (!checkOnly) {
    await rm(resolve(componentDir, 'implementation.ts'), { force: true })
    await rm(resolve(componentDir, 'styles.ts'), { force: true })
  }
}

const publicComponents = [
  ...componentNames.map((name) => `import type ${name} from '../components/${name}'`),
  '',
  ...componentNames.map((name) => `export { default as ${name} } from '../components/${name}'`),
  '',
  'export interface McUIGlobalComponents {',
  ...componentNames.map((name) => `  ${name}: typeof ${name}`),
  ...componentNames.map((name) => `  '${kebabCase(name)}': typeof ${name}`),
  '}',
  '',
  "declare module '@vue/runtime-core' {",
  '  export interface GlobalComponents extends McUIGlobalComponents {}',
  '}',
  '',
].join('\n')
await emit(resolve(generatedDir, 'public-components.ts'), publicComponents)

const registry = [
  "import type { McComponentRegistry } from '../framework/createMcUI'",
  `import { ${componentNames.join(', ')} } from './public-components'`,
  '',
  'const mcComponents: McComponentRegistry = {',
  ...componentNames.map((name) => `  ${name},`),
  '}',
  '',
  'export default mcComponents',
  '',
].join('\n')
await emit(resolve(generatedDir, 'component-registry.ts'), registry)

const aggregate = [
  '/* Generated by scripts/generate-components.mjs. Do not edit directly. */',
  "@import './component-core.css';",
  ...sharedStyles.map((file) => `@import './shared/${file}';`),
  ...componentNames.map((name) => `@import '../components/${name}/component.css';`),
  '',
].join('\n')
await emit(resolve(stylesDir, 'components.css'), aggregate)

const tags = componentNames
  .map((symbol) => ({
    name: kebabCase(symbol),
    ...metadata[symbol],
    source: { module: rootPackage.name, symbol },
  }))
  .sort((left, right) => left.name.localeCompare(right.name))
const webTypes = {
  $schema: 'https://json.schemastore.org/web-types',
  name: rootPackage.name,
  version: rootPackage.version,
  framework: 'vue',
  'description-markup': 'markdown',
  'js-types-syntax': 'typescript',
  contributions: { html: { tags } },
}
await emit(resolve(rootDir, 'web-types.json'), `${JSON.stringify(webTypes, null, 2)}\n`)

const packageExports = {
  '.': { types: './dist/index.d.ts', import: './dist/index.js' },
  ...Object.fromEntries(publicEntries.styles.map((style) => [`./styles/${style}`, `./dist/styles/${style}`])),
  ...Object.fromEntries(
    componentNames.map((name) => [
      `./components/${name}`,
      {
        types: `./dist/components/${name}.d.ts`,
        import: `./dist/components/${name}.js`,
      },
    ]),
  ),
  ...Object.fromEntries(
    publicEntries.composables.map((name) => [
      `./composables/${name}`,
      {
        types: `./dist/composables/${name}.d.ts`,
        import: `./dist/composables/${name}.js`,
      },
    ]),
  ),
  ...Object.fromEntries(
    publicEntries.icons.map((name) => [
      `./icons/${name}`,
      {
        types: `./dist/icons/${name}.d.ts`,
        import: `./dist/icons/${name}.js`,
      },
    ]),
  ),
  ...Object.fromEntries(
    publicEntries.sounds.map((name) => [
      `./sounds/${name}`,
      {
        types: `./dist/sounds/${name}.d.ts`,
        import: `./dist/sounds/${name}.js`,
      },
    ]),
  ),
}
const packageOutput = `${JSON.stringify({ ...rootPackage, exports: packageExports }, null, 2)}\n`
await emit(packageFile, packageOutput)

process.stdout.write(
  `${checkOnly ? 'Checked' : 'Generated'} ${componentNames.length} public components and package entries.\n`,
)
